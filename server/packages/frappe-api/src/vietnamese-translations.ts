function wordTranslation(word: string): string | undefined {
  return wordTranslations[word] ?? extendedWordTranslations[word];
}

const vietnameseMarks = /[ăâđêôơưáàảãạấầẩẫậắằẳẵặéèẻẽẹếềểễệíìỉĩịóòỏõọốồổỗộớờởỡợúùủũụứừửữựýỳỷỹỵ]/i;
const wordPattern = /[A-Za-z][A-Za-z'-]*/g;

/** True for short human-facing English-ish labels, false for codes/identifiers/Vietnamese text. */
export function isLikelyEnglishUiSource(source: string): boolean {
  const text = String(source ?? "").trim();
  if (!text || vietnameseMarks.test(text)) return false;
  if (text.length > 120) return false; // prose is not handled by the token fallback
  if (/^[A-Z0-9_./:+-]+$/.test(text) && !/\s/.test(text)) return false;
  const exact = VIETNAMESE_ERP_TRANSLATIONS[text];
  if (exact) return exact !== text;
  const words = text.match(wordPattern) ?? [];
  if (!words.length) return false;
  const known = words.filter((word) => wordTranslation(word.toLowerCase())).length;
  return known >= Math.max(1, Math.ceil(words.length * 0.4));
}

/**
 * Translate one source string for Vietnamese UI.
 *
 * Exact entries are preferred because Vietnamese word order differs from English. For a short new
 * label that is not yet curated, translate known ERP terms in-place as a fail-soft safety net. We
 * intentionally leave sentences, codes and unknown identifiers untouched instead of pretending to
 * have a trustworthy machine translation.
 */
export function translateVietnameseSource(source: string): string {
  const raw = String(source ?? "");
  const text = raw.trim();
  if (!text) return raw;

  const exactTranslation = VIETNAMESE_ERP_TRANSLATIONS[text];
  if (exactTranslation) return exactTranslation;
  if (!isLikelyEnglishUiSource(text)) return raw;

  let changed = false;
  let translated = text.replace(wordPattern, (word) => {
    const replacement = wordTranslation(word.toLowerCase());
    if (!replacement) return word;
    changed = true;
    return replacement;
  });
  if (!changed) return raw;

  // A few safe order fixes make generic labels readable without trying to be a sentence translator.
  translated = translated
    .replace(/^mặc định\s+(.+)$/i, "$1 mặc định")
    .replace(/^cha\s+(.+)$/i, "$1 cha")
    .replace(/^nguồn\s+(.+)$/i, "$1 nguồn")
    .replace(/^đích\s+(.+)$/i, "$1 đích");

  if (/^[A-Z]/.test(text)) translated = translated.charAt(0).toLocaleUpperCase("vi") + translated.slice(1);
  return translated;
}
