const KEY = "metaforge-locale";
function readLocale(): Locale {
  try { const v = localStorage.getItem(KEY); return v === "en" ? "en" : "vi"; } catch { return "vi"; }
}

interface I18nCtx {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string, fallback?: string) => string;
}
const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({ children, initial }: { children: ReactNode; initial?: Locale }) {
  const [locale, setLocaleState] = useState<Locale>(initial ?? readLocale());
  const value = useMemo<I18nCtx>(() => ({
    locale,
    setLocale: (l) => { try { localStorage.setItem(KEY, l); } catch { /* ignore */ } setLocaleState(l); },
    t: (key, fallback) => DICT[key]?.[locale] ?? DICT[key]?.vi ?? fallback ?? key,
  }), [locale]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

/** Dùng khi CÓ provider (trong app). Fallback an toàn nếu ngoài provider (t = key/fallback). */
export function useI18n(): I18nCtx {
  return useContext(Ctx) ?? { locale: "vi", setLocale: () => {}, t: (k, f) => DICT[k]?.vi ?? f ?? k };
}
export function useT(): (key: string, fallback?: string) => string {
  return useI18n().t;
}
export function useLocale(): [Locale, (l: Locale) => void] {
  const { locale, setLocale } = useI18n();
  return [locale, setLocale];
}
